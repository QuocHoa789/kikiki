#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build a combined runtime script from the luraphruntime modules.

Assembles the 4-file dynamic deobfuscation runtime (envlog.luau + datatypes.luau
+ unicode_data.luau) around a protected Luraph script so `luau combined.luau`
executes the payload against a fake Roblox environment and prints the
reconstructed readable Luau source between \0ENVLOG-BEGIN / \0ENVLOG-END.

Usage:
  python3 build_runtime.py <protected.lua> <combined_out.luau> [key=val ...]

Options (key=val, forwarded to __CONFIG):
  serve=1        run the REPL serve loop instead of one-shot
  inline_probe=1 dump last N opcodes after an error (needs __OPDUMP support)
  dump_strings=1 also print every collected string constant
  prelude=CODE   Lua code that runs untraced before the script
  max_stmts=N    statement budget (default 250000)
  time_budget=N  seconds (default 30)

Note: envlog.luau expects globals __SOURCE (protected script), __CONFIG,
__ROBLOX (datatypes/enums/classes) and __UNICODE (decomp/ccc/comp tables);
this builder provides all of them.
"""

import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME = os.path.join(HERE, 'runtime')


def lua_str(s):
    """Encode a Python string as a Lua long-bracket string."""
    # pick a bracket level that does not appear in the source
    for lvl in range(0, 6):
        eq = '=' * lvl
        if f"]{eq}]" not in s:
            return f"[{eq}[{s}]{eq}]"
    raise ValueError("cannot find a safe long-bracket level")


def build(protected_path, out_path, cfg_pairs):
    src = open(protected_path, encoding='utf-8', errors='replace').read()
    envlog = open(os.path.join(RUNTIME, 'envlog.luau'),
                  encoding='utf-8').read()
    datatypes = open(os.path.join(RUNTIME, 'datatypes.luau'),
                     encoding='utf-8').read()
    unicode_data = open(os.path.join(RUNTIME, 'unicode_data.luau'),
                        encoding='utf-8').read()

    cfg = {}
    for pair in cfg_pairs:
        if '=' not in pair:
            sys.exit(f"bad option (want key=val): {pair}")
        k, v = pair.split('=', 1)
        cfg[k] = v

    # Roblox API data (classes/enums for GetService validation + proxies):
    # generated once; embed directly so the runtime works offline
    roblox_data = open(os.path.join(RUNTIME, 'roblox_api_data.luau'),
                       encoding='utf-8').read()
    cfg_fields = []
    for k, v in cfg.items():
        if v in ('1', '0', 'true', 'false'):
            vv = 'true' if v in ('1', 'true') else 'false'
        elif re.fullmatch(r"-?\d+(\.\d+)?", v):
            vv = v  # numeric option: keep as a number
        else:
            vv = lua_str(v)
        cfg_fields.append(f"{k} = {vv}")

    prelude = f"""--!nocheck
-- generated by build_runtime.py from {os.path.basename(protected_path)}
__SOURCE = {lua_str(src)}
__CONFIG = {{ {', '.join(cfg_fields)} }}
__ROBLOX = (function()
    -- datatypes.luau needs the native vector library
    local ok, dt = pcall(function() return (function()
{datatypes}
    end)() end)
    -- Roblox API data (enums/classes): from gen_roblox_data.py
    local ok2, api = pcall(function() return (function()
{roblox_data}
    end)() end)
    if ok2 then
        return {{ datatypes = ok and dt or nil,
                  enums = api.enums, classes = api.classes }}
    end
    return {{ enums = "", classes = "" }}
end)()
__UNICODE = (function()
    local ok, u = pcall(function() return (function()
{unicode_data}
    end)() end)
    if ok then return u end
    return {{ decomp = "", ccc = "", comp = "" }}
end)()

-- ===== envlog runtime (dynamic deobfuscation) =====
{envlog}
"""
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(prelude)
    print(f"combined written: {out_path} ({len(prelude)}B)")


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    build(sys.argv[1], sys.argv[2], sys.argv[3:])
